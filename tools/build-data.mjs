// Build js/data/<profile>.js from the pinned tables in tools/sources.json.
//
//   node tools/build-data.mjs            build every profile
//   node tools/build-data.mjs --check    fail if a committed data file is out of date
//
// Each output file is a classic script (the app also runs from file://) that registers one
// profile on globalThis.D2LOOTER_DATA, and works as a CommonJS module for the tests.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildModel } from './lib/model.mjs';
import { loadSources, profileTables, ROOT } from './lib/source.mjs';

// Facts about each ruleset that are not in its tables. Sources are listed in NOTICE.
export const PROFILE_META = {
  'lod-114d': { order: 1, label: 'Diablo II: LoD 1.14d', ladderSeason: null, experimental: false },
  // Blizzard News, "Diablo II: Resurrected Ladder Season 15 Now Live": patch 3.3, Season 15 from 2026-08-21.
  'd2r-base': { order: 2, label: 'D2R 3.3 (LoD ruleset)', ladderSeason: 15, experimental: false },
  'd2r-rotw': { order: 3, label: 'D2R 3.3 Reign of the Warlock', ladderSeason: 15, experimental: true },
};

export async function buildAll({ offline = false } = {}) {
  const src = loadSources();
  const out = {};
  for (const id of Object.keys(src.profiles)) {
    const tables = await profileTables(id, { offline });
    const meta = { ...PROFILE_META[id] };
    const model = buildModel(id, meta, tables);
    model.order = meta.order;
    model.source = {
      repo: src.d2data.repo,
      commit: src.profiles[id].commit,
      files: Object.fromEntries(Object.entries(src.profiles[id].files).filter(([k]) => k !== 'atomic').map(([k, path]) => [path, src.profiles[id].sha256[k]])),
    };
    out[id] = model;
  }
  return out;
}

// js/profiles.js: the small list the app needs before it loads a profile's data file.
export function renderProfiles(models) {
  const list = Object.values(models).sort((a, b) => a.order - b.order).map((m) => ({
    id: m.id,
    label: m.label,
    game: m.game,
    experimental: m.experimental,
    ladderSeason: m.ladderSeason,
    file: `js/data/${m.id}.js`,
    commit: m.source.commit,
    counts: { uniques: m.uniques.length, setItems: m.setItems.length, runewords: m.runewords.length, tcs: m.tcs.length },
  }));
  return `// Generated by tools/build-data.mjs. Do not edit.
(function (root) {
  'use strict';
  var profiles = ${JSON.stringify(list, null, 2)};
  root.D2LOOTER_PROFILES = profiles;
  if (typeof module === 'object' && module.exports) module.exports = profiles;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
}

export function render(model) {
  return `// Generated by tools/build-data.mjs from ${model.source.repo}@${model.source.commit}. Do not edit.
(function (root) {
  'use strict';
  var data = ${JSON.stringify(model)};
  (root.D2LOOTER_DATA = root.D2LOOTER_DATA || {})[data.id] = data;
  if (typeof module === 'object' && module.exports) module.exports = data;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, '/')}` || process.argv[1].endsWith('build-data.mjs')) {
  const check = process.argv.includes('--check');
  const models = await buildAll({ offline: process.argv.includes('--offline') });
  const dir = join(ROOT, 'js', 'data');
  mkdirSync(dir, { recursive: true });
  let stale = 0;
  for (const [id, model] of Object.entries(models)) {
    const file = join(dir, `${id}.js`);
    const text = render(model);
    if (check) {
      if (!existsSync(file) || readFileSync(file, 'utf8') !== text) { console.error(`stale: js/data/${id}.js`); stale++; }
      continue;
    }
    writeFileSync(file, text);
    console.log(`js/data/${id}.js  ${(text.length / 1024).toFixed(0)} KB  items ${model.items.length}, uniques ${model.uniques.length}, set items ${model.setItems.length}, TCs ${model.tcs.length}, monsters ${Object.keys(model.monsters).length}, areas ${model.levels.length}, runewords ${model.runewords.length}`);
  }
  const pfile = join(ROOT, 'js', 'profiles.js');
  const ptext = renderProfiles(models);
  if (check) { if (!existsSync(pfile) || readFileSync(pfile, 'utf8') !== ptext) { console.error('stale: js/profiles.js'); stale++; } }
  else writeFileSync(pfile, ptext);
  if (check && stale) process.exit(1);
}
